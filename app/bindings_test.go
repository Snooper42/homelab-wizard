// The frontend's types for the Go side, generated from the App methods
// Wails binds and the events app.go sends: web/types/backend.d.ts. The
// test fails when it is out of date; -update writes it:
//
//	cd app && go test -run TestBindings -update .
var update = flag.Bool("update", false, "rewrite web/types/backend.d.ts")

// events are the payload of each event the Go side sends the frontend.
var events = []struct {
	name    string
	payload any
}{
	{"navigate", ""},
	{"refresh", nil},
	{"progress", install.Event{}},
	{"link", wiring.Link{}},
	{"install:log", ""},
	{"setup:log", ""},
	{"cli:log", ""},
	{"cli:step", ui.StepEvent{}},
	{"status:changed", engine.Change{}},
	{"app:update", (*PendingUpdate)(nil)},
}

func TestBindings(t *testing.T) {
	got := bindings()
	file := filepath.Join("..", "web", "types", "backend.d.ts")
	if *update {
		if err := os.WriteFile(file, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, _ := os.ReadFile(file)
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is out of date: cd app && go test -run TestBindings -update .", file)
	}
}

// tsTypes collects the named Go types the declarations refer to, by
// TypeScript name ("api.Status").
type tsTypes struct {
	decl map[string]string // namespace → name → body, flattened as "ns.name"
	seen map[reflect.Type]string
}

func bindings() []byte {
	ts := &tsTypes{decl: map[string]string{}, seen: map[reflect.Type]string{}}
	var methods []string
	app := reflect.TypeOf(&App{})
	for i := 0; i < app.NumMethod(); i++ {
		m := app.Method(i)
		var params []string
		for j := 1; j < m.Type.NumIn(); j++ {
			params = append(params, fmt.Sprintf("arg%d: %s", j, ts.of(m.Type.In(j))))
		}
		result := "void"
		var outs []reflect.Type
		for j := 0; j < m.Type.NumOut(); j++ {
			if out := m.Type.Out(j); out != reflect.TypeOf((*error)(nil)).Elem() {
				outs = append(outs, out)
			}
		}
		if len(outs) == 1 {
			result = ts.of(outs[0])
		}
		methods = append(methods, fmt.Sprintf("    %s(%s): Promise<%s>;", m.Name, strings.Join(params, ", "), result))
	}
	var evs []string
	for _, e := range events {
		payload := "void"
		if e.payload != nil {
			payload = ts.of(reflect.TypeOf(e.payload))
		}
		evs = append(evs, fmt.Sprintf("    %q: %s;", e.name, payload))
	}

	var b bytes.Buffer
	b.WriteString("// Generated by TestBindings in app/bindings_test.go from the methods Wails\n")
	b.WriteString("// binds and the events app.go sends; do not edit. To update it:\n")
	b.WriteString("//   cd app && go test -run TestBindings -update .\n\n")
	// One namespace per Go package, its types sorted.
	byNS := map[string][]string{}
	for full, body := range ts.decl {
		ns, name, _ := strings.Cut(full, ".")
		byNS[ns] = append(byNS[ns], fmt.Sprintf("  interface %s %s", name, body))
	}
	var spaces []string
	for ns := range byNS {
		spaces = append(spaces, ns)
	}
	sort.Strings(spaces)
	for _, ns := range spaces {
		sort.Strings(byNS[ns])
		fmt.Fprintf(&b, "declare namespace %s {\n%s\n}\n\n", ns, strings.Join(byNS[ns], "\n"))
	}
	fmt.Fprintf(&b, "/** The Go methods the frontend calls: window.go.main.App. */\ninterface Backend {\n%s\n}\n\n", strings.Join(methods, "\n"))
	fmt.Fprintf(&b, "/** Each event the Go side sends, and what it carries. */\ninterface BackendEvents {\n%s\n}\n", strings.Join(evs, "\n"))
	return b.Bytes()
}

// of is the TypeScript type for t, declaring the named structs it meets.
func (ts *tsTypes) of(t reflect.Type) string {
	switch t {
	case reflect.TypeOf(time.Time{}), reflect.TypeOf(time.Duration(0)):
		if t == reflect.TypeOf(time.Duration(0)) {
			return "number"
		}
		return "string"
	case reflect.TypeOf(json.RawMessage{}):
		return "unknown"
	}
	switch t.Kind() {
	case reflect.Pointer:
		return ts.of(t.Elem()) + " | null"
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 {
			return "string" // base64, as encoding/json writes it
		}
		return wrap(ts.of(t.Elem())) + "[]"
	case reflect.Map:
		return "Record<string, " + ts.of(t.Elem()) + ">"
	case reflect.Interface:
		return "unknown"
	case reflect.Struct:
		if t.Name() == "" {
			return ts.fields(t)
		}
		name := path.Base(t.PkgPath()) + "." + t.Name()
		if _, ok := ts.seen[t]; !ok {
			ts.seen[t] = name
			ts.decl[name] = ts.fields(t)
		}
		return name
	}
	return "unknown"
}

// fields is a struct's JSON shape: its json names, optional when omitempty,
// with embedded structs flattened.
func (ts *tsTypes) fields(t reflect.Type) string {
	var lines []string
	var walk func(t reflect.Type)
	walk = func(t reflect.Type) {
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			tag := f.Tag.Get("json")
			name, opts, _ := strings.Cut(tag, ",")
			if !f.IsExported() || name == "-" {
				continue
			}
			if f.Anonymous && name == "" && f.Type.Kind() == reflect.Struct {
				walk(f.Type)
				continue
			}
			if name == "" {
				name = f.Name
			}
			opt := ""
			if strings.Contains(opts, "omitempty") || strings.Contains(opts, "omitzero") {
				opt = "?"
			}
			typ := ts.of(f.Type)
			if strings.Contains(opts, "string") {
				typ = "string"
			}
			lines = append(lines, fmt.Sprintf("    %s%s: %s;", name, opt, typ))
		}
	}
	walk(t)
	if len(lines) == 0 {
		return "{}"
	}
	return "{\n" + strings.Join(lines, "\n") + "\n  }"
}

// wrap brackets a union before [] makes it an array.
func wrap(s string) string {
	if strings.Contains(s, "|") {
		return "(" + s + ")"
	}
	return s
}
